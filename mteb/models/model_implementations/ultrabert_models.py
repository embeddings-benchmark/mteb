def ultrabert_embed_loader(
    model_name_or_path: str, revision: str, **kwargs: Any
) -> InstructSentenceTransformerModel:
    from transformers.utils import is_flash_attn_2_available

    attn = "flash_attention_2" if is_flash_attn_2_available() else "sdpa"
    model_kwargs = {"attn_implementation": attn, **kwargs.pop("model_kwargs", {})}
    return InstructSentenceTransformerModel(
        model_name_or_path, revision=revision, model_kwargs=model_kwargs, **kwargs
    )


